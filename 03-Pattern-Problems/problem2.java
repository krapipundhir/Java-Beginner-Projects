// Printing a increasing pattern of stars-(row wise), it seems like a Right angle Triangle.

public class problem2 {
    public static void main(String args[]){
        int n=5;
        for(int i=1;i<=n;i++){
            for(int j=1;j<=i;j++){

                System.out.print("*");

            }
            
            System.out.println();










        }
          




















    }
















    
}
