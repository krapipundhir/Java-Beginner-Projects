// Inverted Half Pyramid rotaed by 180 degree.

public class problem4 {
    public static void main(String args[]){

        
        int m=4;
        for (int j=1;j<=m;j++){
            for(int i=1;i<=m-j;i++){
                System.out.print(" ");
            }    
            for(int i=1;i<=j;i++) {
                System.out.print("*");
            }   
            System.out.println();



            

            


                










        }















    }

    
















    
}
