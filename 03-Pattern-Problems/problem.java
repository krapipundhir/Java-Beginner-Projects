// printing a hollow Rectangle of Stars.

public class problem {
    public static void main(String args[]){
        int x = 5;
        int y=4;
        
        for(int i=1;i<=x;i++){
            for(int j=1;j<=y;j++){
                


                
            
                if(i==1 || j==1 || i==x || j==y){
                System.out.print("*");
                }else{
                    System.out.print(" ");
                }
            }System.out.println();





        }




















    }















    
}
